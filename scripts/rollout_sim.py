"""Staged rollout simulation: SHADOW -> ASSISTED -> canary -> AUTO_LOW_RISK.

Runs the golden cases through the real pipeline in each autonomy mode and writes
docs/rollout.md from the measured numbers. "Human decisions" in the shadow comparison are the
golden labels (synthetic analysts); real agreement must be re-measured on production shadow
traffic before the first promotion. LLM is the label-blind stub unless cassettes exist.
"""

import argparse
import asyncio
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from opspod.domain.enums import AutonomyMode  # noqa: E402
from opspod.evals import harness  # noqa: E402
from opspod.evals.metrics import CaseResult  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
STAGES = [
    ("1. Shadow", AutonomyMode.SHADOW, 100),
    ("2. Assisted", AutonomyMode.ASSISTED, 100),
    ("3. Canary 25%", AutonomyMode.AUTO_LOW_RISK, 25),
    ("4. Auto low-risk", AutonomyMode.AUTO_LOW_RISK, 100),
]


def agreement(results: list[CaseResult]) -> float:
    ok = sum(r.checks["outcome"] and r.checks["route"] for r in results)
    return ok / len(results)


def stage_stats(name: str, results: list[CaseResult], mode: AutonomyMode) -> dict[str, object]:
    n = len(results)
    by = lambda route: sum(r.actual["route"] == route for r in results)  # noqa: E731
    money_cases = [r for r in results if r.paid > 0]
    return {
        "stage": name,
        "mode": mode.value,
        "cases": n,
        "agreement_with_human_label": agreement(results),
        "would_route_auto": by("auto") / n,
        "would_route_approval": by("approval") / n,
        "would_route_escalate": by("escalate") / n,
        "cases_where_money_moved": len(money_cases),
        "money_moved_minor_units": sum(r.paid for r in results),
        "unauthorized_actions": sum(r.unauthorized_action for r in results),
        "crashes": sum(1 for r in results if r.error),
    }


def render(
    rows: list[dict[str, object]],
    by_type: dict[str, float],
    by_region: dict[str, float],
    disagreements: list[str],
    meta: dict[str, object],
) -> str:
    def pct(v: object) -> str:
        return f"{float(v):.1%}"  # type: ignore[arg-type]

    lines = [
        "# Rollout plan and evidence",
        "",
        "Generated by `scripts/rollout_sim.py` from "
        f"{meta['n']} golden cases (dev + holdout + hand-written), LLM: **{meta['llm']}**.",
        "",
        "> The simulated humans are the golden labels, and the LLM is a label-blind stub, so this "
        "shows the *mechanics* of each stage and the safety invariants, not production "
        "agreement. Agreement must be re-measured on real shadow traffic before promoting.",
        "",
        "## Stages, exit criteria and measured evidence",
        "",
        "| Stage | Mode | Agreement | Auto | Auto share of eligible | Approval | Escalate | "
        "Cases where money moved | Unauthorized actions |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    eligible = float(rows[0]["would_route_auto"])  # what shadow says could auto-execute
    for r in rows:
        lines.append(
            f"| {r['stage']} | {r['mode']} | {pct(r['agreement_with_human_label'])} | "
            f"{pct(r['would_route_auto'])} | "
            f"{pct(float(r['would_route_auto']) / eligible) if eligible else 'n/a'} | "
            f"{pct(r['would_route_approval'])} | "
            f"{pct(r['would_route_escalate'])} | {r['cases_where_money_moved']} | "
            f"{r['unauthorized_actions']} |"
        )
    shadow = rows[0]
    lines += [
        "",
        "Shadow mode computes the decision the agent *would* take and moves no money: "
        f"{shadow['cases_where_money_moved']} cases moved money in the shadow run.",
        "",
        "## Promotion criteria",
        "",
        "| From -> to | Must hold for 7 consecutive days |",
        "|---|---|",
        "| Shadow -> Assisted | agreement on outcome+route >= 95%; 0 `PolicyViolationBlocked` "
        "alerts; 0 pipeline crashes; every disagreement reviewed |",
        "| Assisted -> Canary | approver override rate < 5%; approval wait p95 within SLA; "
        "reversal rate < 1%; no unresolved dead letters |",
        "| Canary (25%) -> Auto | canary reversal rate no worse than the assisted baseline; "
        "no unauthorized-action incidents; auto-resolve rate on target |",
        "| Any -> lower | any page-severity alert, `PolicyViolationBlocked > 0`, or reversal "
        "spike: set the mode back one stage (or `KILL_SWITCH`) first, investigate second |",
        "",
        "Override rate and reversal rate need real humans and cannot be measured here; they are "
        "exit criteria to be measured in production.",
        "",
        "## Shadow agreement by case type",
        "",
        "| Case type | Agreement |",
        "|---|---|",
    ]
    lines += [f"| {k} | {v:.1%} |" for k, v in sorted(by_type.items())]
    lines += ["", "## Shadow agreement by region", "", "| Region | Agreement |", "|---|---|"]
    lines += [f"| {k} | {v:.1%} |" for k, v in sorted(by_region.items())]
    lines += ["", "## Shadow disagreements", ""]
    lines += [f"- {d}" for d in disagreements[:20]] or ["None in this run."]
    lines += [
        "",
        "## Controls available at every stage",
        "",
        "- Mode and canary percentage: `PUT /v1/admin/flags` (per region and case type "
        "overrides supported).",
        '- Kill switch: `PUT /v1/admin/flags {"kill_switch": true}` routes everything to humans '
        "and disables LLM calls immediately, mid-case included.",
        "- Reversal: `POST /v1/actions/{id}/reverse` creates a compensating ledger entry.",
        "",
    ]
    return "\n".join(lines)


async def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--llm", choices=["stub", "replay"], default="stub")
    args = ap.parse_args()
    cases = harness.load_cases("all")
    by_id = {c["id"]: c for c in cases}
    rows: list[dict[str, object]] = []
    shadow_results: list[CaseResult] = []
    for name, mode, canary in STAGES:
        results, _ = await harness.run_eval(cases, llm=args.llm, mode=mode, canary=canary)
        rows.append(stage_stats(name, results, mode))
        if mode is AutonomyMode.SHADOW:
            shadow_results = results
        print(
            f"{name}: agreement={rows[-1]['agreement_with_human_label']:.1%} "
            f"money_cases={rows[-1]['cases_where_money_moved']}"
        )
    by_type: dict[str, list[bool]] = {}
    by_region: dict[str, list[bool]] = {}
    disagree: list[str] = []
    for r in shadow_results:
        ok = r.checks["outcome"] and r.checks["route"]
        by_type.setdefault(by_id[r.id]["case_type"], []).append(ok)
        by_region.setdefault(r.region, []).append(ok)
        if not ok:
            disagree.append(
                f"`{r.id}` {r.tags}: human {r.expected['route']}/{r.expected['outcome']} "
                f"vs agent {r.actual['route']}/{r.actual['outcome']}"
            )
    avg = lambda xs: sum(xs) / len(xs)  # noqa: E731
    meta = {"n": len(cases), "llm": "stub (label-blind)" if args.llm == "stub" else "cassettes"}
    doc = render(
        rows,
        {k: avg(v) for k, v in by_type.items()},
        {k: avg(v) for k, v in by_region.items()},
        disagree,
        meta,
    )
    (ROOT / "docs" / "rollout.md").write_text(doc, encoding="utf-8", newline="\n")
    (ROOT / "evals" / "results" / "rollout.json").write_text(
        json.dumps(rows, indent=1) + "\n", encoding="utf-8", newline="\n"
    )
    print("wrote docs/rollout.md")


if __name__ == "__main__":
    asyncio.run(main())
