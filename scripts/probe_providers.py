"""Probe free LLM providers; write config/llm.yaml and docs/provider-notes.md.

Lists free models, tests JSON-schema output, measures latency and 429s.
Keeps calls few to protect free-tier quotas. Keys from env only.
"""

import os
import time
from datetime import UTC, datetime
from pathlib import Path

import httpx
import yaml

ROOT = Path(__file__).resolve().parent.parent
MAX_MODELS = 4  # per provider
PROBE_PROMPT = 'Reply with JSON {"label": "ok", "n": 3}.'
SCHEMA = {
    "type": "object",
    "properties": {"label": {"type": "string"}, "n": {"type": "integer"}},
    "required": ["label", "n"],
}
OR_BASE = "https://openrouter.ai/api/v1"
GEM_BASE = "https://generativelanguage.googleapis.com/v1beta"


def probe_openrouter(key: str) -> list[dict]:
    models = httpx.get(f"{OR_BASE}/models", timeout=30).json()["data"]
    free = [m["id"] for m in models if m["id"].endswith(":free")]
    out = []
    for mid in free[:MAX_MODELS]:
        body = {
            "model": mid,
            "messages": [{"role": "user", "content": PROBE_PROMPT}],
            "temperature": 0,
            "response_format": {
                "type": "json_schema",
                "json_schema": {"name": "probe", "schema": SCHEMA, "strict": True},
            },
        }
        out.append(
            _timed(
                mid,
                "openrouter",
                f"{OR_BASE}/chat/completions",
                body,
                {"Authorization": f"Bearer {key}"},
                _or_ok,
            )
        )
    return out


def probe_gemini(key: str) -> list[dict]:
    hdr = {"x-goog-api-key": key}
    models = httpx.get(f"{GEM_BASE}/models", headers=hdr, timeout=30).json().get("models", [])
    names = [
        m["name"].removeprefix("models/")
        for m in models
        if "generateContent" in m.get("supportedGenerationMethods", []) and ("flash" in m["name"])
    ]
    out = []
    for mid in names[:MAX_MODELS]:
        body = {
            "contents": [{"parts": [{"text": PROBE_PROMPT}]}],
            "generationConfig": {
                "temperature": 0,
                "responseMimeType": "application/json",
                "responseSchema": {
                    "type": "OBJECT",
                    "properties": {"label": {"type": "STRING"}, "n": {"type": "INTEGER"}},
                    "required": ["label", "n"],
                },
            },
        }
        out.append(
            _timed(mid, "gemini", f"{GEM_BASE}/models/{mid}:generateContent", body, hdr, _gem_ok)
        )
    return out


def _or_ok(r: dict) -> bool:
    return _json_ok(r["choices"][0]["message"]["content"])


def _gem_ok(r: dict) -> bool:
    return _json_ok(r["candidates"][0]["content"]["parts"][0]["text"])


def _json_ok(text: str) -> bool:
    import json

    try:
        d = json.loads(text)
        return d.get("label") == "ok" and isinstance(d.get("n"), int)
    except (ValueError, AttributeError):
        return False


def _timed(model, provider, url, body, headers, check) -> dict:
    t0 = time.monotonic()
    res = {
        "provider": provider,
        "model": model,
        "json_ok": False,
        "status": None,
        "latency_s": None,
        "retry_after": None,
    }
    try:
        r = httpx.post(url, json=body, headers=headers, timeout=60)
        res["status"] = r.status_code
        res["retry_after"] = r.headers.get("retry-after")
        if r.status_code == 200:
            res["json_ok"] = check(r.json())
    except (httpx.HTTPError, KeyError, IndexError, ValueError) as e:
        res["status"] = type(e).__name__
    res["latency_s"] = round(time.monotonic() - t0, 2)
    return res


def write_outputs(results: list[dict], skipped: list[str]) -> None:
    good = sorted((r for r in results if r["json_ok"]), key=lambda r: r["latency_s"])
    chain = [{"provider": r["provider"], "model": r["model"]} for r in good]
    # Fast model for classify/draft, stronger (slowest working) for analyze; humans tune later.
    cfg = {
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "tasks": {
            "classify": list(chain),
            "analyze": list(reversed(chain)),
            "draft_message": list(chain),
        },
        # Limits are placeholders until measured from provider docs / 429 behaviour.
        "limits": {
            p: {"requests_per_minute": 10, "daily_calls": 900}
            for p in {r["provider"] for r in good}
        },
    }
    (ROOT / "config" / "llm.yaml").write_text(yaml.safe_dump(cfg, sort_keys=False))
    lines = ["# Provider notes", "", f"Generated by `make probe` at {cfg['generated_at']}.", ""]
    lines += [f"- Skipped (no key): {s}" for s in skipped]
    lines += [
        "",
        "| provider | model | status | json schema ok | latency s | retry-after |",
        "|---|---|---|---|---|---|",
    ]
    lines += [
        f"| {r['provider']} | {r['model']} | {r['status']} | {r['json_ok']} | "
        f"{r['latency_s']} | {r['retry_after']} |"
        for r in results
    ]
    lines += ["", "Free-tier prompts may be used by providers for training; all data is synthetic."]
    (ROOT / "docs" / "provider-notes.md").write_text("\n".join(lines) + "\n")


def main() -> None:
    results, skipped = [], []
    if key := os.getenv("OPENROUTER_API_KEY"):
        results += probe_openrouter(key)
    else:
        skipped.append("openrouter (OPENROUTER_API_KEY unset)")
    if key := os.getenv("GEMINI_API_KEY"):
        results += probe_gemini(key)
    else:
        skipped.append("gemini (GEMINI_API_KEY unset)")
    write_outputs(results, skipped)
    print(f"probed {len(results)} models; skipped: {skipped or 'none'}")


if __name__ == "__main__":
    main()
